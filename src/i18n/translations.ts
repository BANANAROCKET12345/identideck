export type TranslationKey = keyof typeof translations.zh;

export function translate(
  lang: Language,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dict = translations[lang] ?? translations.zh;
  let template: string = dict[key] ?? translations.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

export function getAuthMethodLabel(lang: Language, method: AuthMethod): string {
  return translate(lang, `auth_${method}` as TranslationKey);
}

export function getBillingCycleLabel(
  lang: Language,
  cycle: BillingCycle,
  short = false,
): string {
  return translate(
    lang,
    `${short ? 'cycleShort' : 'cycle'}_${cycle}` as TranslationKey,
  );
}

export function getCategoryLabel(
  lang: Language,
  category: ServiceCategory | 'all',
): string {
  return translate(lang, `cat_${category}` as TranslationKey);
}

export function useT() {
  const language = useVaultStore((s) => s.language);
  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) =>
      translate(language, key, params),
    [language],
  );
  return { t, language };
}
