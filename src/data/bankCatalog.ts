export const BANK_BY_ID: Record<string, BankPreset> = Object.fromEntries(
  BANK_CATALOG.map((bank) => [bank.id, bank]),
);

export function getBankPresetById(bankId?: string): BankPreset | undefined {
  if (!bankId) return undefined;
  return BANK_BY_ID[bankId.trim().toLowerCase()];
}

export function searchBanks(
  query: string,
  region: BankRegion | 'digital' | 'all' = 'all',
): BankPreset[] {
  const q = query.trim().toLowerCase();
  return BANK_CATALOG.filter((bank) => {
    if (region === 'digital') {
      if (!bank.isDigitalBank) return false;
    } else if (region !== 'all' && bank.region !== region) {
      return false;
    }
    if (!q) return true;
    return (
      bank.nameEn.toLowerCase().includes(q) ||
      bank.nameZh.toLowerCase().includes(q) ||
      bank.id.toLowerCase().includes(q) ||
      bank.domain.toLowerCase().includes(q) ||
      bank.aliases.some((alias) => alias.toLowerCase().includes(q))
    );
  });
}
