export function getServiceById(
  serviceId: string,
  fallbackName?: string,
  fallbackDomain?: string,
): ServiceCatalogItem {
  const normalized = serviceId.trim().toLowerCase();
  const aliasedId = SERVICE_ID_ALIASES[normalized] ?? serviceId;
  const found = SERVICE_BY_ID[aliasedId] ?? SERVICE_BY_ID[normalized];
  if (found) return found;
  return inferCustomServiceMeta(fallbackName ?? serviceId.replace(/^custom:/, ''), fallbackDomain);
}

export function searchServices(
  query: string,
  category: ServiceCategory | 'all' = 'all',
): ServiceCatalogItem[] {
  const q = query.trim().toLowerCase();
  return SERVICE_CATALOG.filter((item) => {
    if (category !== 'all' && item.category !== category) {
      return false;
    }
    if (!q) return true;
    return (
      item.name.toLowerCase().includes(q) ||
      item.nameZh.toLowerCase().includes(q) ||
      item.id.toLowerCase().includes(q) ||
      item.monogram.toLowerCase().includes(q) ||
      (item.domain?.toLowerCase().includes(q) ?? false) ||
      item.aliases.some((alias) => alias.toLowerCase().includes(q))
    );
  });
}
