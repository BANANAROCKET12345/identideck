const CUSTOM_PALETTE = [
  '#1E3A5F',
  '#0F4C3A',
  '#0369A1',
  '#334155',
  '#B45309',
  '#0E7490',
  '#1D4ED8',
  '#047857',
];

function stableHash(input: string): number {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash);
}

export function extractCleanDomain(raw: string): string | undefined {
  const trimmed = raw.trim();
  if (!trimmed) return undefined;
  const candidate = trimmed.includes('://') ? trimmed : `https://${trimmed}`;
  if (!trimmed.includes('.')) return undefined;
  try {
    const url = new URL(candidate);
    return url.hostname.replace(/^www\./i, '').toLowerCase();
  } catch {
    return undefined;
  }
}

export function createCustomServiceId(nameOrUrl: string): string {
  const domain = extractCleanDomain(nameOrUrl);
  const base = (domain ?? nameOrUrl)
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `custom:${base || 'app'}`;
}

export function inferCustomServiceMeta(
  nameOrUrl: string,
  explicitDomain?: string,
): ServiceCatalogItem {
  const trimmed = nameOrUrl.trim() || 'Custom App';
  const domain = explicitDomain?.trim() || extractCleanDomain(trimmed);

  let displayName = trimmed;
  if (domain && (trimmed.startsWith('http://') || trimmed.startsWith('https://') || trimmed === domain)) {
    const firstLabel = domain.split('.')[0] ?? domain;
    displayName = firstLabel.charAt(0).toUpperCase() + firstLabel.slice(1);
  }

  const asciiLetters = displayName.replace(/[^A-Za-z0-9]/g, '');
  let monogram = 'APP';
  if (asciiLetters.length >= 2) {
    const words = displayName.split(/\s+/).filter(Boolean);
    if (words.length >= 2 && /^[A-Za-z]/.test(words[0]) && /^[A-Za-z]/.test(words[1])) {
      monogram = `${words[0][0]}${words[1][0]}`.toUpperCase();
    } else {
      monogram = asciiLetters.slice(0, 3).toUpperCase();
    }
  } else {
    monogram = Array.from(displayName).slice(0, 2).join('').toUpperCase() || 'AP';
  }

  const serviceId = createCustomServiceId(domain ?? displayName);
  const brandColor = CUSTOM_PALETTE[stableHash(serviceId) % CUSTOM_PALETTE.length];

  return {
    id: serviceId,
    name: displayName,
    nameZh: displayName,
    category: 'productivity',
    brandColor,
    textColor: '#FFFFFF',
    monogram,
    domain,
    aliases: [displayName.toLowerCase(), ...(domain ? [domain] : [])],
  };
}

